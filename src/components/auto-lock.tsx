"use client";

import { useEffect } from "react";
import { logout } from "@/actions/auth";
import { LOCK_AFTER_MS, shouldLock } from "@/lib/lock";

/**
 * ที่เก็บเวลาที่ปิดแอปครั้งล่าสุด
 *
 * ⚠️ ต้องเป็น localStorage ห้ามเป็น sessionStorage
 *    sessionStorage ถูกล้างทิ้งเมื่อ iOS ปิดแอปที่ค้างอยู่เพื่อคืนหน่วยความจำ
 *    ซึ่งคือสิ่งที่เกิดขึ้นพอดีเมื่อวางเครื่องทิ้งไว้นานๆ — กรณีที่ตัวล็อก
 *    มีไว้กันโดยเฉพาะ ผลคือยิ่งทิ้งไว้นานยิ่งไม่ล็อก ตรงข้ามกับที่ต้องการ
 *
 * คีย์นี้ใช้ร่วมกันสองตัวในไฟล์นี้ จึงอยู่ไฟล์เดียวกัน ถ้าแยกไฟล์แล้วชื่อคีย์
 * หลุดจากกันเมื่อไร ตัวล็อกจะเงียบไปเลยโดยไม่มีอะไรฟ้อง
 */
const KEY = "ledger_hidden_at";

const remember = () => {
  try {
    localStorage.setItem(KEY, String(Date.now()));
  } catch {
    // เขียนไม่ได้ (โหมดส่วนตัวบางเบราว์เซอร์) ก็ล็อกไม่ได้ ไม่ถึงตาย
  }
};

const forget = () => {
  try {
    localStorage.removeItem(KEY);
  } catch {
    // อ่านเขียนไม่ได้ก็ไม่มีค่าค้างให้ต้องล้างอยู่แล้ว
  }
};

/**
 * อ่านแล้วลบทิ้งทันที
 *
 * ต้องลบเพราะหลังถูกล็อกแล้วกรอก PIN ใหม่ หน้าจะกลับมาแล้ว AutoLock
 * ขึ้นอีกรอบ ถ้าค่าเก่ายังอยู่มันจะเห็นเวลาเดิมแล้วล็อกซ้ำทันที
 * กลายเป็นวนไม่จบ กรอก PIN แล้วเด้งออกทุกครั้ง
 */
const takeHiddenAt = (): number | null => {
  try {
    const saved = localStorage.getItem(KEY);
    localStorage.removeItem(KEY);
    if (saved === null) return null;
    const n = Number(saved);
    return Number.isFinite(n) ? n : null;
  } catch {
    return null;
  }
};

/**
 * ล็อกแอปเมื่อปิดทิ้งไว้เกิน 15 นาที ต้องกรอก PIN ใหม่
 *
 * อายุ session นับจากตอนกรอก PIN ไม่ได้นับจากตอนวางเครื่อง เครื่องที่วาง
 * อยู่หน้าร้านจึงเปิดดูยอดขายได้ทั้งวัน ตัวนี้ปิดช่องนั้น
 *
 * จับสองจังหวะ
 *   ตอนแอปถูกซ่อนหรือปิด  จดเวลาไว้
 *   ตอนแอปกลับมาหรือเปิดใหม่  เทียบเวลา เกินกำหนดก็ล็อก
 *
 * ⚠️ ต้องแปะไว้ทุกหน้าที่ต้องล็อกอิน ไม่ใช่แค่ใน (app)
 *    นาฬิกาเดินอยู่ใน localStorage ตลอด แต่คนที่หยุดมันได้มีแค่ตัวนี้
 *    หน้าไหนที่ล็อกอินแล้วแต่ไม่มีตัวนี้ เวลาที่ค้างอยู่จะแก่ขึ้นเรื่อยๆ
 *    โดยไม่มีใครล้าง แล้วไปเด้งใส่หน้าถัดไปแทน — /shops เคยเป็นแบบนั้น
 *    ส่วนหน้า /login ใช้ LockReset ข้างล่างแทน
 *
 * ⚠️ ต้องเช็คตอนคอมโพเนนต์ขึ้นด้วย ไม่ใช่รอแต่ visibilitychange
 *    เพราะเวลา iOS ปิดแอปทิ้งแล้วเปิดใหม่ หน้าถูกโหลดใหม่ทั้งใบในสภาพ
 *    "มองเห็นอยู่แล้ว" — visibilitychange ไม่มีวันยิง ถ้ารอแต่ตัวนั้น
 *    การเปิดแอปหลังทิ้งไว้ข้ามคืนจะไม่ล็อกเลย
 *
 * ⚠️ นี่คือกลอนประตู ไม่ใช่ตู้เซฟ
 *    ตัวจับทำงานฝั่งหน้าจอ ใครที่ยิง request เองเป็นยังเข้าได้จนกว่า session
 *    จะหมดอายุจริง กันคนหยิบเครื่องไปกดเล่นได้ ไม่ได้กันคนที่ตั้งใจเจาะ
 *
 * ⚠️ ล็อกแล้วของที่พิมพ์ค้างในฟอร์มหายด้วย ต่างจาก VersionWatch ที่ยอมเลื่อน
 *    ออกไปถ้ามีของค้าง เพราะการล็อกคือสิ่งที่ต้องเกิดให้ได้
 */
export function AutoLock() {
  useEffect(() => {
    const check = () => {
      if (document.visibilityState !== "visible") return;
      if (!shouldLock({ hiddenAt: takeHiddenAt(), now: Date.now(), afterMs: LOCK_AFTER_MS })) return;
      // logout ลบ cookie ฝั่งเซิร์ฟเวอร์แล้วพาไปหน้ากรอก PIN
      void logout();
    };

    const onVisibility = () => {
      if (document.visibilityState === "hidden") remember();
      else check();
    };

    document.addEventListener("visibilitychange", onVisibility);

    /**
     * pagehide ด้วย เพราะ iOS ไม่ได้ยิง visibilitychange เสมอไปตอนที่มันตัดสินใจ
     * แช่แข็งหรือปิดแอปที่ค้างอยู่ ถ้าพลาดจังหวะจดเวลา จะไม่มีอะไรให้เทียบ
     * ตอนกลับมา แล้วก็จะไม่ล็อก
     */
    window.addEventListener("pagehide", remember);

    // เช็คทันทีตอนขึ้น — ครอบกรณีเปิดแอปใหม่หลังถูก iOS ปิดทิ้ง
    check();

    return () => {
      document.removeEventListener("visibilitychange", onVisibility);
      window.removeEventListener("pagehide", remember);
    };
  }, []);

  return null;
}

/**
 * ล้างนาฬิกาการล็อก ใช้เฉพาะบนหน้ากรอก PIN
 *
 * ที่ต้องมีเพราะจังหวะที่ถูกล็อกออกมา เบราว์เซอร์ยิง pagehide ระหว่างเด้ง
 * ไปหน้า PIN ซึ่ง AutoLock จดเวลาไว้อีกครั้งก่อนตาย แล้วหน้า PIN ไม่มีใคร
 * ล้างค่านั้น ถ้าเจ้าของร้านวางเครื่องคาหน้า PIN ไว้เกิน 15 นาทีแล้วค่อย
 * กลับมากรอก จะโดนเด้งกลับมาหน้าเดิมทันทีที่เข้าแอปได้ กรอกกี่ครั้งก็เด้ง
 * จนกว่าจะกรอกเร็วพอ — อาการที่ดูเหมือนแอปพังมากกว่าดูเหมือนระบบกันขโมย
 * (ทดสอบซ้ำได้ ตั้งค่าคีย์ให้เก่า 20 นาที แล้วกรอก PIN)
 *
 * เหตุผลเชิงความหมายก็ตรงกัน — ยืนอยู่หน้าประตูที่ล็อกแล้ว ไม่มี session
 * ค้างให้ต้องนับเวลาถอยหลังอีก อะไรที่เกิดหลังจากนี้เริ่มนับหนึ่งใหม่หมด
 */
export function LockReset() {
  useEffect(forget, []);
  return null;
}
