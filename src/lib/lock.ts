/**
 * กติกาการล็อกแอปเมื่อปิดทิ้งไว้นาน
 *
 * ต่างจากอายุ session ที่นับจากตอนกรอก PIN — อันนั้นบอกว่า "ล็อกอินได้นาน
 * แค่ไหน" ส่วนอันนี้บอกว่า "วางเครื่องทิ้งไว้ได้นานแค่ไหนก่อนต้องกรอกใหม่"
 *
 * ที่ต้องมีเพราะเครื่องวางอยู่ที่หน้าร้าน ใครหยิบไปตอนเจ้าของหันหลังก็เปิดดู
 * ยอดขายทั้งเดือนได้ทันที ในขณะที่อายุ session หนึ่งวันไม่ได้กันอะไรตรงนั้นเลย
 *
 * ⚠️ วิธีทำงานเปลี่ยนไปแล้ว อ่านก่อนแก้
 *
 * เดิมจดเวลาที่ปิดแอปไว้ใน localStorage แล้วให้ฝั่งหน้าจอเทียบเวลาเองตอน
 * กลับมา ซึ่งใช้ได้แต่ช้าและรั่ว — กว่า React จะติดตั้งเสร็จแล้วเรียก logout
 * วิ่งไปกลับเซิร์ฟเวอร์ หน้าที่เซิร์ฟเวอร์ส่งมาแล้วก็โชว์ยอดเงินค้างอยู่
 * 2-3 วินาที ให้คนที่หยิบเครื่องไปอ่านได้สบายๆ ก่อนเด้งไปหน้า PIN
 * (เจ้าของร้านเจอเองแล้วทักมา)
 *
 * ตอนนี้ใช้ cookie ที่หมดอายุเองแทน แล้วให้เซิร์ฟเวอร์เป็นคนตัดสินตั้งแต่
 * ก่อนสร้าง HTML — ไม่มี HTML ของหน้าที่ล็อกอยู่ถูกส่งออกมาเลยสักไบต์
 *
 * ที่เลือก "หมดอายุเอง" แทนการจดเวลาแล้วเทียบ เพราะสองข้อ
 *   • เบราว์เซอร์ลบให้เองเมื่อครบเวลา ไม่ต้องเทียบนาฬิกาสองฝั่งที่อาจไม่ตรงกัน
 *   • พังไปทางที่ปลอดภัย — ลบ cookie ทิ้งเองได้ แต่ผลคือ "ล็อกเร็วขึ้น"
 *     ไม่ใช่ "ไม่ล็อก" ต่างจากการจดเวลาที่แก้ค่าให้เป็นอนาคตแล้วรอดได้
 */

/**
 * ปิดทิ้งไว้เกินเท่านี้แล้วต้องกรอก PIN ใหม่
 *
 * 15 นาทีเป็นค่าที่เจ้าของร้านเลือก — ยาวพอให้สลับไปรับไลน์ ตอบลูกค้า
 * หรือไปหยิบของแล้วกลับมาโดยไม่ต้องกรอกใหม่ แต่สั้นพอที่เครื่องซึ่งถูกวางทิ้ง
 * ไว้จะล็อกตัวเองก่อนใครจะได้เปิดดู
 */
export const AWAKE_MAX_AGE_SECONDS = 15 * 60;

/**
 * cookie ที่บอกว่า "แอปยังตื่นอยู่"
 *
 * ตั้งใจไม่ใช่ httpOnly เพราะฝั่งหน้าจอต้องต่ออายุมันเองระหว่างใช้งาน
 * ไม่ใช่ความลับ มีแค่ค่า "1" — ตัวที่เป็นความลับจริงคือ ledger_session
 * ซึ่งยังเป็น httpOnly เหมือนเดิม
 */
export const AWAKE_COOKIE = "ledger_awake";

/**
 * ⚠️ นี่คือกลอนประตู ไม่ใช่ตู้เซฟ
 *
 * คนที่เปิด devtools เป็นแล้วเซ็ต cookie เองยังเข้าได้จนกว่า session จริง
 * จะหมดอายุ กันคนหยิบเครื่องไปกดเล่นได้ ไม่ได้กันคนที่ตั้งใจเจาะ
 * ทุกทางที่อ่านข้อมูลร้านได้ถูกปิดด้วย cookie นี้หมดแล้ว รวม /api/export
 */

/**
 * บรรทัดที่ฝั่งหน้าจอเอาไปยัดใส่ document.cookie เพื่อต่ออายุ
 *
 * แยกออกมาเป็นฟังก์ชันบริสุทธิ์เพราะถ้าเขียนผิดสักตัว cookie จะไม่ถูกเซ็ต
 * โดยไม่มีอะไรฟ้อง แล้วอาการที่เจอคือ "ใช้ไปสักพักแล้วเด้งออกเอง"
 * ซึ่งไล่หาสาเหตุยากมาก
 *
 * secure ใส่เฉพาะตอนเป็น https — ถ้าใส่ตอนรันที่ localhost แบบ http
 * เบราว์เซอร์จะทิ้ง cookie เงียบๆ แล้ว dev จะเด้งออกทุก 15 นาทีโดยไม่รู้ว่าทำไม
 */
export function awakeCookie(https: boolean): string {
  const parts = [
    `${AWAKE_COOKIE}=1`,
    "path=/",
    `max-age=${AWAKE_MAX_AGE_SECONDS}`,
    "samesite=lax",
  ];
  if (https) parts.push("secure");
  return parts.join("; ");
}
