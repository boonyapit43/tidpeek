/**
 * กติกาการล็อกแอปเมื่อปิดทิ้งไว้นาน
 *
 * ต่างจากอายุ session ที่นับจากตอนกรอก PIN — อันนั้นบอกว่า "ล็อกอินได้นาน
 * แค่ไหน" ส่วนอันนี้บอกว่า "วางเครื่องทิ้งไว้ได้นานแค่ไหนก่อนต้องกรอกใหม่"
 *
 * ที่ต้องมีเพราะเครื่องวางอยู่ที่หน้าร้าน ใครหยิบไปตอนเจ้าของหันหลังก็เปิดดู
 * ยอดขายทั้งเดือนได้ทันที ในขณะที่อายุ session หนึ่งวันไม่ได้กันอะไรตรงนั้นเลย
 *
 * แยกออกมาเป็นฟังก์ชันบริสุทธิ์เพราะเป็นตรรกะที่ผิดแล้วเจ็บสองทาง — ล็อกถี่
 * เกินไปคือต้องกรอก PIN ทุกครั้งที่สลับไปดูไลน์ ส่วนไม่ล็อกเลยคือไม่มีอะไรกัน
 */

/**
 * ปิดทิ้งไว้เกินเท่านี้แล้วต้องกรอก PIN ใหม่
 *
 * 15 นาทีเป็นค่าที่เจ้าของร้านเลือก — ยาวพอให้สลับไปรับไลน์ ตอบลูกค้า
 * หรือไปหยิบของแล้วกลับมาโดยไม่ต้องกรอกใหม่ แต่สั้นพอที่เครื่องซึ่งถูกวางทิ้ง
 * ไว้จะล็อกตัวเองก่อนใครจะได้เปิดดู
 */
export const LOCK_AFTER_MS = 15 * 60 * 1000;

export function shouldLock({
  hiddenAt,
  now,
  afterMs = LOCK_AFTER_MS,
}: {
  /** เวลาที่แอปถูกสลับออกไปครั้งล่าสุด null = ยังไม่เคยออกไปเลย */
  hiddenAt: number | null;
  now: number;
  afterMs?: number;
}): boolean {
  // ยังไม่เคยออกไป (เพิ่งเปิดหน้าใหม่) ไม่มีอะไรให้ตัดสิน
  if (hiddenAt === null) return false;

  /**
   * เวลาในอนาคตแปลว่านาฬิกาเครื่องถูกปรับ หรือค่าที่เก็บไว้เพี้ยน
   * ไม่ล็อก เพราะการล็อกคนที่กำลังใช้งานอยู่แย่กว่าการไม่ล็อกหนึ่งครั้ง
   */
  if (hiddenAt > now) return false;

  return now - hiddenAt >= afterMs;
}
