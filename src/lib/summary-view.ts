import { monthOf, yearOf } from "./date";

export type SummaryView = "day" | "week" | "month" | "year";

/**
 * หน้าสรุปเป็นหน้าแรกของแอป — เปิดมาต้องเจอตัวเลข ไม่ใช่หน้าว่าง
 *
 * เดิมเปิดที่ "วันนี้" ตายตัว ซึ่งตอนเช้าที่ยังไม่ได้ลงรายการคือหน้าว่างพอดี
 * (คนใช้เจอเองแล้วทักมา) กติกาใหม่: เลือกช่วงที่แคบที่สุดที่ยังมีข้อมูล
 *
 *   วันนี้มีรายการแล้ว        → วัน     โฟกัสของสดใหม่
 *   วันนี้ว่าง เดือนนี้มี      → เดือน   เห็นภาพรวมพลางรอลงรายการแรก
 *   เดือนนี้ว่าง ปีนี้มี       → ปี      เช้าวันที่ 1 ของเดือนก็ยังมีของให้ดู
 *   ยังไม่เคยมีรายการเลย     → เดือน   หน้าว่างพร้อมทางไปเริ่มบันทึก
 *
 * ใช้เฉพาะตอนเปิดหน้าโดยไม่ระบุมุมมองใน URL — กดแท็บเลือกเองเมื่อไหร่
 * ก็ได้ตามที่กดเสมอ ความฉลาดนี้จึงไม่มีทางขวางการใช้งานตรงๆ
 */
export function defaultSummaryView(latestTxnDate: string | null, today: string): SummaryView {
  if (!latestTxnDate) return "month";
  if (latestTxnDate >= today) return "day";
  if (monthOf(latestTxnDate) === monthOf(today)) return "month";
  if (yearOf(latestTxnDate) === yearOf(today)) return "year";

  // ร้านที่หยุดใช้ข้ามปี — ปีนี้ว่างเปล่า พาไปดูปีที่มีของไม่ได้จากตรงนี้
  // (มุมมองผูกกับปีปัจจุบัน) จึงเปิดเดือนไว้เป็นจุดเริ่มลงรายการใหม่
  return "month";
}
