/**
 * กติกาการแบ่งลิสต์ยาวออกเป็นชุดๆ
 *
 * เดิมลิสต์ยาวๆ ถูกตัดเงียบๆ ที่เพดานของ query แล้วหยุดเฉยๆ ไม่มีอะไรบอก
 * ซึ่งอันตรายกว่าลิสต์ยาว — วัดจริงที่ข้อมูล 75 วัน หน้าบัญชีมีความเคลื่อนไหว
 * 128 รายการแต่โชว์ 60 คนเลื่อนจนสุดแล้วสรุปว่า "ไม่มีรายการก่อนหน้านี้"
 * ทั้งที่ยังมีอีก 68 รายการ ซึ่งเป็นการเข้าใจผิดเรื่องเงินที่ไม่มีทางรู้ตัว
 *
 * แก้ด้วยสองอย่างคู่กันเสมอ — จำกัดจำนวนที่โหลด และบอกความจริงว่ามีทั้งหมด
 * เท่าไหร่ ขาดอย่างใดอย่างหนึ่งไม่ได้
 */

/** จำนวนแถวต่อหนึ่งชุด ~10 วันของร้านที่ลงวันละห้ารายการ */
export const PAGE_SIZE = 50;

/**
 * เพดานสูงสุดที่ยอมโหลดในหน้าเดียว ต่อให้แก้ตัวเลขใน URL เอง
 *
 * กันไม่ให้ ?n=999999 ลากทั้งฐานข้อมูลมาวาดเป็น DOM ก้อนเดียว ซึ่งบนมือถือ
 * คือหน้าค้าง คนที่อยากได้ครบจริงๆ มีปุ่มส่งออก Excel ซึ่งเหมาะกับงานนั้นกว่า
 */
export const MAX_ROWS = 1000;

/**
 * อ่านจำนวนแถวที่จะแสดงจาก ?n= ใน URL
 *
 * ค่าใน URL แก้เองได้ ต้องกันทั้งค่าที่ไม่ใช่ตัวเลข ค่าติดลบ และค่ามหาศาล
 * ปัดขึ้นเป็นจำนวนเท่าของ PAGE_SIZE เพื่อให้ ?n=53 ที่พิมพ์มั่วยังได้ชุดที่
 * ลงตัวเหมือนกดปุ่มปกติ ลิสต์จึงไม่มีสถานะแปลกๆ ที่เกิดจาก URL อย่างเดียว
 */
export function rowsToShow(raw: string | undefined): number {
  const n = Number.parseInt(raw ?? "", 10);
  if (!Number.isFinite(n) || n <= PAGE_SIZE) return PAGE_SIZE;

  const rounded = Math.ceil(n / PAGE_SIZE) * PAGE_SIZE;
  return Math.min(rounded, MAX_ROWS);
}

/**
 * ลิงก์ของชุดถัดไป — คงพารามิเตอร์เดิมทุกตัวไว้ เปลี่ยนแค่ n
 *
 * ต้องคงของเดิมไว้ทั้งหมด ไม่งั้นกด "ดูเพิ่ม" ในผลค้นหาที่กรองเฉพาะรายจ่าย
 * แล้วตัวกรองหลุด กลายเป็นเห็นทุกรายการ ซึ่งดูเผินๆ เหมือนโหลดเพิ่มสำเร็จ
 */
export function moreHref(params: URLSearchParams, shown: number): string {
  const next = new URLSearchParams(params);
  next.set("n", String(shown + PAGE_SIZE));
  return `?${next.toString()}`;
}
