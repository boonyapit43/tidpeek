import { describe, expect, it } from "vitest";
import { currentMonth, today, weekOf } from "./date";
import { resolvePeriod } from "./export-period";

/**
 * ตัวแปลลิงก์ส่งออกเป็นช่วงเวลา
 *
 * ลิงก์พวกนี้ถูกแชร์ต่อ ถูกบุ๊กมาร์ก และถูกแก้มือในแถบที่อยู่ ค่าที่วิ่งเข้ามา
 * จึงเป็นอะไรก็ได้ กติกาที่ต้องจริงเสมอมีสองข้อ
 *
 *   • ค่าเสียต้องไม่ทำให้หน้าจอแดง — ตกกลับมาเป็นเดือนปัจจุบันเสมอ
 *   • ค่าดีต้องได้ช่วงตรงตามที่ขอ ไม่ใช่ช่วงใกล้เคียง
 */

const at = (query: string) => resolvePeriod(new URLSearchParams(query));

describe("ช่วงที่ระบุมาถูกต้อง", () => {
  it("รายวัน", () => {
    expect(at("p=day&d=2026-08-28").period).toEqual({ day: "2026-08-28" });
  });

  it("รายเดือน", () => {
    expect(at("p=month&m=2026-08").period).toEqual({ month: "2026-08" });
  });

  it("รายปี", () => {
    expect(at("p=year&y=2026").period).toEqual({ year: "2026" });
  });

  it("ช่วงกำหนดเอง", () => {
    expect(at("from=2026-08-01&to=2026-08-15").period).toEqual({
      from: "2026-08-01",
      to: "2026-08-15",
    });
  });

  it("วันเดียวก็เป็นช่วงที่ถูกต้อง ไม่ใช่ค่าเสีย", () => {
    expect(at("from=2026-08-05&to=2026-08-05").period).toEqual({
      from: "2026-08-05",
      to: "2026-08-05",
    });
  });
});

describe("สัปดาห์", () => {
  it("ส่งวันจันทร์มา ได้สัปดาห์นั้น", () => {
    // 2026-08-24 เป็นวันจันทร์
    expect(at("p=week&w=2026-08-24").period).toEqual({ week: "2026-08-24" });
  });

  /**
   * สัปดาห์แทนด้วยวันจันทร์เสมอ ถ้าปล่อยวันกลางสัปดาห์ผ่านเข้าไปตรงๆ
   * ชื่อไฟล์จะบอกช่วงหนึ่ง แต่ข้อมูลข้างในเป็นอีกช่วง
   */
  it("ส่งวันกลางสัปดาห์มา ก็ดึงกลับไปหาวันจันทร์ให้", () => {
    expect(at("p=week&w=2026-08-27").period).toEqual({ week: "2026-08-24" });
  });

  it("ชื่อไฟล์ของสัปดาห์บอกทั้งวันเริ่มและวันจบ", () => {
    expect(at("p=week&w=2026-08-24").slug).toBe("2026-08-24_ถึง_2026-08-30");
  });
});

describe("ค่าที่ใช้ไม่ได้ ต้องตกกลับมาเป็นเดือนปัจจุบัน", () => {
  const month = { month: currentMonth() };

  it("ไม่ส่งอะไรมาเลย", () => {
    expect(at("").period).toEqual(month);
  });

  it("เดือนผิดรูปแบบ", () => {
    expect(at("p=month&m=สิงหาคม").period).toEqual(month);
  });

  it("ปีผิดรูปแบบ", () => {
    expect(at("p=year&y=26").period).toEqual(month);
  });

  it("สัปดาห์ผิดรูปแบบ", () => {
    expect(at("p=week&w=2026-W35").period).toEqual(month);
  });

  it("ช่วงที่มีแค่ฝั่งเดียว", () => {
    expect(at("from=2026-08-01").period).toEqual(month);
    expect(at("to=2026-08-01").period).toEqual(month);
  });

  /**
   * กรอกสลับกันมา ต้องไม่แอบสลับกลับให้
   *
   * ถ้าสลับให้เงียบๆ คนจะได้ไฟล์ที่ไม่ตรงกับสิ่งที่กรอก แล้วเชื่อว่าตรง
   * ตกกลับมาเป็นเดือนปัจจุบันซึ่งมีป้ายบอกช่วงชัดเจนในไฟล์ ปลอดภัยกว่า
   */
  it("ช่วงที่วันจบมาก่อนวันเริ่ม", () => {
    expect(at("from=2026-08-15&to=2026-08-01").period).toEqual(month);
  });
});

describe("ค่าเสียเฉพาะรายวัน ตกกลับเป็นวันนี้ ไม่ใช่เดือนนี้", () => {
  // เพราะคนกดมาจากแท็บ "วัน" ถ้าเด้งไปเป็นทั้งเดือนจะได้ไฟล์ใหญ่กว่าที่คิดมาก
  it("วันผิดรูปแบบ", () => {
    expect(at("p=day&d=พรุ่งนี้").period).toEqual({ day: today() });
  });
});

describe("ป้ายกำกับและชื่อไฟล์", () => {
  it("ป้ายของช่วงกำหนดเองบอกทั้งสองวันเป็นภาษาไทย", () => {
    const { label } = at("from=2026-08-01&to=2026-08-15");

    expect(label).toBe("เสาร์ 1 สิงหาคม 2569 ถึง เสาร์ 15 สิงหาคม 2569");
    expect(label).toContain("ถึง");
  });

  it("ชื่อไฟล์ไม่มีอักขระที่ห้ามใช้ในชื่อไฟล์ของ Windows", () => {
    const slugs = [
      at("p=day&d=2026-08-28").slug,
      at(`p=week&w=${weekOf("2026-08-27")}`).slug,
      at("p=month&m=2026-08").slug,
      at("p=year&y=2026").slug,
      at("from=2026-08-01&to=2026-08-15").slug,
    ];

    for (const slug of slugs) {
      expect(slug).not.toMatch(/[\/:*?"<>|]/);
      expect(slug.length).toBeGreaterThan(0);
    }
  });
});
