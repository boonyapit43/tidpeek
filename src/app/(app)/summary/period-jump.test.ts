import { describe, expect, it } from "vitest";
import { hrefFor } from "./period-jump";

/**
 * เลือกวันจากปฏิทินแล้วไปที่ช่วงไหน
 *
 * กติกาคือ "วันไหนก็ได้ในช่วงที่อยากไป" — มุมมองสัปดาห์เลือกวันพุธก็ต้องพา
 * ไปสัปดาห์นั้น ไม่ใช่บังคับให้หาวันจันทร์ให้เจอก่อน
 *
 * ผิดตรงนี้แล้วอาการที่เห็นคือ "เลือกวันแล้วไปโผล่คนละช่วง" ซึ่งคนจะโทษว่า
 * ปฏิทินเพี้ยน ทั้งที่ปฏิทินส่งค่าถูก
 */
describe("เลือกวันแล้วไปช่วงที่ครอบวันนั้น", () => {
  it("มุมมองวัน ไปวันนั้นตรงๆ", () => {
    expect(hrefFor("day", "2024-03-15")).toBe("/summary?p=day&d=2024-03-15");
  });

  /** 2026-09-02 เป็นวันพุธ สัปดาห์ของมันเริ่มวันจันทร์ที่ 31 ส.ค. */
  it("มุมมองสัปดาห์ เลือกวันกลางสัปดาห์ก็ไปสัปดาห์นั้น", () => {
    expect(hrefFor("week", "2026-09-02")).toBe("/summary?p=week&w=2026-08-31");
  });

  it("มุมมองเดือน เลือกวันไหนของเดือนก็ได้", () => {
    expect(hrefFor("month", "2024-03-15")).toBe("/summary?p=month&m=2024-03");
    expect(hrefFor("month", "2024-03-01")).toBe("/summary?p=month&m=2024-03");
  });

  it("มุมมองปี เลือกวันไหนของปีก็ได้", () => {
    expect(hrefFor("year", "2024-12-31")).toBe("/summary?p=year&y=2024");
    expect(hrefFor("year", "2024-01-01")).toBe("/summary?p=year&y=2024");
  });

  /**
   * เคสที่เจ้าของร้านเจอ — อยากย้อนไปปี 2567 ซึ่งเดิมต้องกดลูกศรเป็นสิบครั้ง
   * ตอนนี้เลือกวันเดียวจบ
   */
  it("ย้อนไปหลายปีได้ในครั้งเดียว", () => {
    expect(hrefFor("year", "2024-06-10")).toBe("/summary?p=year&y=2024");
    expect(hrefFor("month", "2024-06-10")).toBe("/summary?p=month&m=2024-06");
  });
});
